/**
 * Main translation engine function
 * @param {string} lang - 'es' or 'en'
 */
function applyTranslations(lang) {
  const selectedLang = (lang === 'en' || lang === 'es') ? lang : 'en';
  localStorage.setItem('esparzas_lang', selectedLang);
  sessionStorage.setItem('esparzas_lang', selectedLang);
  document.documentElement.lang = selectedLang;

  const dict = TRANSLATIONS[selectedLang] || TRANSLATIONS['en'];

  // 1. Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      // If the string contains HTML tags (<br>, <strong>, etc.), use innerHTML
      if (dict[key].includes('<') && dict[key].includes('>')) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // 2. Update placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // 3. Update image alt attributes with data-i18n-alt
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const key = el.getAttribute('data-i18n-alt');
    if (dict[key]) {
      el.alt = dict[key];
    }
  });

  // 4. Update title attributes with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key]) {
      el.title = dict[key];
    }
  });

  // 5. Update aria-label attributes with data-i18n-aria
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (dict[key]) {
      el.setAttribute('aria-label', dict[key]);
    }
  });

  // 6. Update active state of language toggle buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === selectedLang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });
}

/**
 * Initialize internationalization on page load
 */
document.addEventListener('DOMContentLoaded', () => {
  // Always default to English whenever the website is opened.
  // Only maintain Spanish if the user explicitly clicked the language toggle in their current session.
  const explicitLang = sessionStorage.getItem('esparzas_user_selected_lang');
  const activeLang = (explicitLang === 'es') ? 'es' : 'en';

  if (!explicitLang) {
    sessionStorage.setItem('esparzas_lang', 'en');
    localStorage.setItem('esparzas_lang', 'en');
  }

  applyTranslations(activeLang);

  // Bind click handlers to all lang-btn buttons (desktop and mobile drawer)
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = btn.getAttribute('data-lang');
      sessionStorage.setItem('esparzas_user_selected_lang', lang);
      sessionStorage.setItem('esparzas_lang', lang);
      localStorage.setItem('esparzas_lang', lang);
      applyTranslations(lang);
    });
  });
});